/*
  The whole seed is over 2MB, which is more than a single database call will
  accept. So it is emitted twice: once as one reviewable file, and once as
  numbered chunks small enough to apply one at a time.

  Each chunk is a complete transaction that sets its own workflow GUCs, because a
  pooled connection gives no guarantee that a session setting survives between
  calls. A chunk therefore either applies fully or not at all, and if one fails
  part way through the run the remove script cleans up whatever landed.
*/
const chunks = [];
let current = null;

function startChunk(name, options = {}) {
  current = { name, lines: [], stageGateWorkflow: Boolean(options.stageGateWorkflow) };
  chunks.push(current);
}

function say(line = "") {
  out.push(line);
  if (current) current.lines.push(line);
}

/* Preamble lines belong to the single file only: each chunk writes its own. */
function sayFileOnly(line = "") {
  out.push(line);
}

function section(title, note, options = {}) {
  startChunk(title, options);
  say("");
  say(`/* ${"-".repeat(74)}`);
  say(`   ${title}`);
  if (note) {
    say("");
    note.split("\n").forEach((row) => say(`   ${row}`));
  }
  say(`   ${"-".repeat(74)} */`);
  say("");
}

function track(name, n) {
  counts[name] = (counts[name] || 0) + n;
}

/* jsonb literal, dollar-quoted so commentary containing apostrophes is safe. */
function jsonLiteral(value) {
  const json = JSON.stringify(value);
  if (json.includes("$ppm$")) throw new Error("payload contains the dollar-quote tag");
  return `$ppm$${json}$ppm$::jsonb`;
}

function mark(record) {
  return { ...record, [MARKER_FIELD]: MARKER_VALUE };
}

