/*
  STAGE 14A - build the seed SQL.

    node STAGE-14A-DEMO-BUILD.mjs

  Writes STAGE-14A-DEMO-DATA.sql and STAGE-14A-DEMO-DATA-REMOVE.sql.

  Design decisions worth knowing before reading the output:

  1. Nothing that already exists is destroyed. The four real people, the existing
     portfolio and the five programmes are referenced or enriched; PRJ-00001 to
     PRJ-00005 are left completely alone. Every row this seed creates carries
     legacy_payload->>'demoDataSet' = 'STAGE-14A', and the remove script deletes
     strictly by that marker, so it can never take real records with it.

  2. Workflow GUCs are set for the transaction. Approved budgets, approval
     requests and plan baselines are all guarded by triggers that refuse a direct
     write; the guards exist so those fields can only appear through a workflow.
     Setting the GUC is the documented way to seed history, and it is set locally
     so it dies with the transaction.

  3. Stage gates are inserted as Draft and then updated. Their insert guard has no
     escape hatch, so a decided gate genuinely cannot be inserted. Seeding them in
     two steps is not a workaround, it is the only correct path.

  4. auth.uid() is null when this runs from the SQL editor or the Supabase MCP.
     That is deliberate: it makes the guards treat the write as "not from the
     application", which is what allows access roles to be set directly. The
     consequence is that audit_log rows for the seed have no named actor. The
     audit triggers catch that and continue rather than failing.
*/

